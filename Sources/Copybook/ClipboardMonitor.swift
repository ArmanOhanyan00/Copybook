/// Polls the general pasteboard and turns every change into a ClipItem.
@MainActor
final class ClipboardMonitor {
    private let pb = NSPasteboard.general
    private let store: Store
    private var timer: Timer?
    private var lastChange: Int
    private var ignored: Set<Int> = []
    var onCapture: ((ClipItem) -> Void)?

    /// Marker types defined at nspasteboard.org, plus well-known vendor equivalents.
    static let confidentialTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "com.agilebits.onepassword",
        "com.agilebits.onepassword-osx",
        "com.agilebits.onepassword4",
        "com.agilebits.onepassword7",
    ]
    static let transientTypes: Set<String> = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]
    private static let skipTypes: Set<String> = [
        "org.nspasteboard.source",
        "com.apple.is-remote-clipboard",
    ]

    init(store: Store) {
        self.store = store
        lastChange = NSPasteboard.general.changeCount
    }

    func stop() { timer?.invalidate(); timer = nil }

    func start() {
        timer?.invalidate()
        let t = Timer(timeInterval: 0.35, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        t.tolerance = 0.1
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    /// Our own pasteboard writes must not be recaptured.
    func ignore(changeCount: Int) {
        ignored.insert(changeCount)
        if ignored.count > 64 { ignored.removeFirst() }
    }

    private func poll() {
        let c = pb.changeCount
        guard c != lastChange else { return }
        lastChange = c
        if ignored.remove(c) != nil { return }
        guard !Prefs.shared.isPaused else { return }
        capture()
    }

    private func capture() {
        let prefs = Prefs.shared
        let typeIDs = Set((pb.types ?? []).map(\.rawValue))
        guard !typeIDs.isEmpty else { return }
        if prefs.ignoreConfidential, !typeIDs.isDisjoint(with: Self.confidentialTypes) { return }
        if prefs.ignoreTransient, !typeIDs.isDisjoint(with: Self.transientTypes) { return }

        var bundleID = pb.string(forType: .init("org.nspasteboard.source"))
        var appName: String?
        if bundleID?.isEmpty ?? true, let front = NSWorkspace.shared.frontmostApplication {
            bundleID = front.bundleIdentifier
            appName = front.localizedName
        }
        if let b = bundleID {
            // Our own pasteboard writes are already skipped by changeCount, so copies made
            // inside Copybook's windows (e.g. the editor) are still captured here.
            if prefs.ignoredApps.contains(b) { return }
            if appName == nil { appName = AppInfo.name(for: b) }
        }

        var item = ClipItem(kind: .text)
        item.sourceBundleID = bundleID
        item.sourceAppName = appName
        var blobs: [(String, Data)] = []
        var hashSource = Data()

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            item.kind = .file
            item.filePaths = urls.map(\.path)
            item.text = urls.map(\.path).joined(separator: "\n")
            hashSource = Data(("file" + item.text!).utf8)
            if urls.count == 1, let thumb = Self.fileThumbnail(urls[0]) {
                blobs.append(("_thumb", thumb))
                item.hasThumbnail = true
            }
        } else if let string = pb.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            item.text = string
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            if ColorParser.parse(trimmed) != nil {
                item.kind = .color
            } else if !trimmed.contains(where: \.isWhitespace), let url = URL(string: trimmed),
                      let scheme = url.scheme?.lowercased(), ["http", "https"].contains(scheme), url.host != nil {
                item.kind = .link
            } else {
                item.kind = .text
            }
            hashSource = Data((item.kind.rawValue + string).utf8)
            blobs = representations(dropImages: true)
        } else if let imageData = pb.data(forType: .png) ?? pb.data(forType: .tiff) {
            item.kind = .image
            blobs = representations(dropImages: false)
            hashSource = imageData
            if let src = CGImageSourceCreateWithData(imageData as CFData, nil) {
                if let props = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any] {
                    item.imageWidth = props[kCGImagePropertyPixelWidth] as? Int
                    item.imageHeight = props[kCGImagePropertyPixelHeight] as? Int
                }
                if let thumb = Self.thumbnailPNG(src, maxPixel: 640) {
                    blobs.append(("_thumb", thumb))
                    item.hasThumbnail = true
                }
            }
        } else {
            return
        }

        item.contentHash = SHA256.hash(data: hashSource).map { String(format: "%02x", $0) }.joined()
        let (saved, isNew) = store.add(item, blobs: blobs)
        onCapture?(saved)
        if isNew {
            if saved.kind == .image, prefs.recognizeText { Enricher.recognizeText(saved, store: store) }
            if saved.kind == .link, prefs.linkPreviews { Enricher.fetchLinkPreview(saved, store: store) }
        }
    }

    /// Raw data for every type of the first pasteboard item, so rich content pastes back faithfully.
    private func representations(dropImages: Bool) -> [(String, Data)] {
        guard let first = pb.pasteboardItems?.first else { return [] }
        let types = first.types.map(\.rawValue)
        let hasPNG = types.contains("public.png")
        var out: [(String, Data)] = []
        var total = 0
        for raw in types {
            if raw.hasPrefix("dyn.") || Self.skipTypes.contains(raw) { continue }
            if Self.confidentialTypes.contains(raw) || Self.transientTypes.contains(raw) { continue }
            if raw == "public.tiff" && hasPNG { continue } // PNG is enough and far smaller
            if dropImages, let t = UTType(raw), t.conforms(to: .image), types.contains("public.utf8-plain-text") {
                // Text clips (e.g. from spreadsheets) often carry huge rendered images; keep them only if small.
                if let d = first.data(forType: .init(raw)), d.count < 2_000_000 { out.append((raw, d)); total += d.count }
                continue
            }
            guard let d = first.data(forType: .init(raw)) else { continue }
            total += d.count
            if total > 80_000_000 { break }
            out.append((raw, d))
        }
        return out
    }

    nonisolated static func thumbnailPNG(_ src: CGImageSource, maxPixel: Int) -> Data? {
        let opts: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixel,
        ]
        guard let cg = CGImageSourceCreateThumbnailAtIndex(src, 0, opts as CFDictionary) else { return nil }
        return NSBitmapImageRep(cgImage: cg).representation(using: .png, properties: [:])
    }

    static func fileThumbnail(_ url: URL) -> Data? {
        guard let type = UTType(filenameExtension: url.pathExtension), type.conforms(to: .image),
              let src = CGImageSourceCreateWithURL(url as CFURL, nil) else { return nil }
        return thumbnailPNG(src, maxPixel: 640)
    }
}

/// Background enrichment: OCR for images and title/image previews for links.
@MainActor
enum Enricher {
    private static var providers: [UUID: LPMetadataProvider] = [:]

    static func recognizeText(_ item: ClipItem, store: Store) {
        guard let key = store.imageKey(item), let url = store.blobURL(item, key: key) else { return }
        let id = item.id
        DispatchQueue.global(qos: .utility).async {
            guard let src = CGImageSourceCreateWithURL(url as CFURL, nil),
                  let cg = CGImageSourceCreateImageAtIndex(src, 0, nil) else { return }
            let request = VNRecognizeTextRequest()
            request.recognitionLevel = .accurate
            request.usesLanguageCorrection = true
            try? VNImageRequestHandler(cgImage: cg).perform([request])
            let text = (request.results ?? []).compactMap { $0.topCandidates(1).first?.string }.joined(separator: " ")
            guard !text.isEmpty else { return }
            DispatchQueue.main.async { store.mutate(id) { $0.ocrText = text } }
        }
    }

    static func fetchLinkPreview(_ item: ClipItem, store: Store) {
        guard let url = item.linkURL else { return }
        let id = item.id
        let provider = LPMetadataProvider()
        provider.timeout = 12
        providers[id] = provider
        provider.startFetchingMetadata(for: url) { meta, _ in
            let title = meta?.title
            let imageProvider = meta?.imageProvider ?? meta?.iconProvider
            let finish: (Data?) -> Void = { png in
                DispatchQueue.main.async {
                    providers[id] = nil
                    if let png {
                        store.attachBlob(png, key: "_linkImage", to: id) { $0.linkTitle = title; $0.hasLinkImage = true }
                    } else if let title {
                        store.mutate(id) { $0.linkTitle = title }
                    }
                }
            }
            guard let imageProvider else { finish(nil); return }
            imageProvider.loadObject(ofClass: NSImage.self) { obj, _ in
                guard let image = obj as? NSImage, let tiff = image.tiffRepresentation,
                      let src = CGImageSourceCreateWithData(tiff as CFData, nil) else { finish(nil); return }
                finish(ClipboardMonitor.thumbnailPNG(src, maxPixel: 1600))
            }
        }
    }
}
